create table if not exists public.creators (
  id bigint generated by default as identity primary key,
  record_date date,
  creator_id text,
  tiktok_link text,
  email text,
  normalized_email text,
  normalized_tiktok text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists creators_creator_id_idx on public.creators (creator_id);
create index if not exists creators_normalized_email_idx on public.creators (normalized_email);
create index if not exists creators_normalized_tiktok_idx on public.creators (normalized_tiktok);

alter table public.creators enable row level security;

drop policy if exists "authenticated users can read creators" on public.creators;
create policy "authenticated users can read creators" on public.creators
  for select to authenticated using (true);

drop policy if exists "authenticated users can insert creators" on public.creators;
create policy "authenticated users can insert creators" on public.creators
  for insert to authenticated with check (true);

drop policy if exists "authenticated users can update creators" on public.creators;
create policy "authenticated users can update creators" on public.creators
  for update to authenticated using (true) with check (true);

drop policy if exists "authenticated users can delete creators" on public.creators;
create policy "authenticated users can delete creators" on public.creators
  for delete to authenticated using (true);
