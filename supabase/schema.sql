create policy "authenticated users can delete hijack records" on public.hijack_records for delete to authenticated using (true);

create or replace function public.get_hijack_stats()
returns jsonb
language sql stable security invoker set search_path = public
as $$
with grouped as (
  select target, scope, count(*)::integer as total,
    count(*) filter (where replied_at is not null)::integer as replies
  from public.hijack_records group by target, scope
), all_rows as (
  select count(*)::integer as total,
    count(*) filter (where replied_at is not null)::integer as matched_replies
  from public.hijack_records
)
select jsonb_build_object(
  'total', coalesce((select total from all_rows), 0),
  'matchedReplies', coalesce((select matched_replies from all_rows), 0),
  'unknownReplies', 0,
  'byBrand', coalesce((select jsonb_agg(jsonb_build_object('target', target, 'total', total, 'replies', replies) order by replies desc, total desc) from grouped where scope = 'Overall brand'), '[]'::jsonb),
  'byProduct', coalesce((select jsonb_agg(jsonb_build_object('target', target, 'total', total, 'replies', replies) order by replies desc, total desc) from grouped where scope = 'Product'), '[]'::jsonb)
);
$$;

grant execute on function public.get_hijack_stats() to authenticated;

create table if not exists public.brand_catalog (
  id bigint generated by default as identity primary key,
  name text not null unique,
  normalized_name text not null unique,
  aliases jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.brand_catalog_products (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references public.brand_catalog(id) on delete cascade,
  name text not null,
  normalized_name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (brand_id, normalized_name)
);

