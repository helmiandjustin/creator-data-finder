create table if not exists public.creators (
  id bigint generated by default as identity primary key,
  record_date date,
  creator_id text,
  tiktok_link text,
  email text,
  normalized_email text,
  normalized_tiktok text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists creators_creator_id_idx on public.creators (creator_id);
create index if not exists creators_normalized_email_idx on public.creators (normalized_email);
create index if not exists creators_normalized_tiktok_idx on public.creators (normalized_tiktok);

alter table public.creators enable row level security;

drop policy if exists "authenticated users can read creators" on public.creators;
create policy "authenticated users can read creators" on public.creators
  for select to authenticated using (true);

drop policy if exists "authenticated users can insert creators" on public.creators;
create policy "authenticated users can insert creators" on public.creators
  for insert to authenticated with check (true);

drop policy if exists "authenticated users can update creators" on public.creators;
create policy "authenticated users can update creators" on public.creators
  for update to authenticated using (true) with check (true);

drop policy if exists "authenticated users can delete creators" on public.creators;
create policy "authenticated users can delete creators" on public.creators
  for delete to authenticated using (true);

create or replace function public.get_creator_stats()
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
with clock as (
  select (now() at time zone 'Asia/Jakarta')::date as today
), bounds as (
  select date_trunc('month', today)::date as current_start,
    (date_trunc('month', today) - interval '1 month')::date as previous_start,
    (date_trunc('month', today) + interval '1 month')::date as next_start
  from clock
), daily as (
  select c.record_date as date, count(*)::integer as count
  from public.creators c, bounds b
  where c.record_date >= b.current_start and c.record_date < b.next_start
  group by c.record_date
  order by c.record_date
)
select jsonb_build_object(
  'total', (select count(*) from public.creators),
  'current_month', (select count(*) from public.creators c, bounds b where c.record_date >= b.current_start and c.record_date < b.next_start),
  'previous_month', (select count(*) from public.creators c, bounds b where c.record_date >= b.previous_start and c.record_date < b.current_start),
  'daily', coalesce((select jsonb_agg(jsonb_build_object('date', date, 'count', count) order by date) from daily), '[]'::jsonb)
);
$$;

grant execute on function public.get_creator_stats() to authenticated;
